import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {createDataHandler} from '../lib/data-handler.ts';
const sqlite=new DatabaseSync(':memory:');
sqlite.exec(readFileSync('drizzle/0000_records.sql','utf8'));
const prepare=sql=>{let args=[];return {bind(...a){args=a;return this},async all(){return {results:sqlite.prepare(sql).all(...args)}},async run(){return sqlite.prepare(sql).run(...args)}}};
const objects=new Map();
const handler=createDataHandler({DB:{prepare,async batch(statements){for(const s of statements)await s.run()}},BUCKET:{async put(k,v){objects.set(k,v)},async get(k){return objects.has(k)?{text:async()=>objects.get(k)}:null},async delete(k){objects.delete(k)}}});
const request=async(store,method='GET',body,id,origin='https://preview.test')=>handler(new Request('https://preview.test/api/data?'+new URLSearchParams({store,...(id?{id}:{})}),{method,headers:{origin},...(body!==undefined?{body:JSON.stringify(body)}:{})}));
assert.equal((await request('unknown')).status,400);
assert.equal((await request('spaces','PUT',{id:'x',name:'Test'},null,'https://other.test')).status,403);
assert.equal((await request('spaces','PUT',null)).status,400);
assert.equal((await request('photos','DELETE',undefined,'../../file')).status,400);
assert.equal((await request('spaces','PUT',{id:'check-space',name:'Storage test'})).status,200);
assert.equal((await request('tasks','PUT',{id:'check-task',spaceId:'check-space',task:'Task',status:'done',startDate:'<bad>'})).status,400);
assert.equal((await request('tasks','PUT',{id:'check-task',spaceId:'check-space',task:'Task',status:'done',hasPhoto:true})).status,200);
const photo={taskId:'check-task',dataUrl:'data:image/png;base64,aGVsbG8='};
assert.equal((await request('photos','PUT',photo)).status,200);
assert.deepEqual(await (await request('photos','GET',undefined,'check-task')).json(),photo);
assert.equal((await request('photos','PUT',{taskId:'bad-image',dataUrl:'javascript:bad'})).status,400);
const visit={id:'check-visit',spaceId:'check-space',date:'2026-10-23',inspector:'Test',observations:'Observation',outcome:'On track'};
assert.equal((await request('visits','PUT',visit)).status,200);
assert.equal((await request('visits','PUT',{...visit,nextDate:'2026-10-22'})).status,400);
assert.equal((await request('reportHistory','PUT',{id:'check-report',spaceId:'check-space',html:'<h1>Snapshot</h1>'})).status,200);
visit.observations='Updated observation';
await request('visits','PUT',visit);
assert.equal((await (await request('visits','GET',undefined,'check-visit')).json()).observations,'Updated observation');
await request('spaces','DELETE',undefined,'check-space');
for(const store of ['spaces','tasks','visits','photos','reportHistory'])assert.deepEqual(await (await request(store)).json(),[]);
assert.equal(objects.size,0);
console.log('Storage checks passed: record updates, photo round-trip, invalid inputs, origin protection and project deletion cascade.');
sqlite.close();
